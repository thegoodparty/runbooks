"""Publish PMF experiment manifests to s3://agent-experiment-metadata-{env}/.

Reads `experiments/<id>/{manifest.json,instruction.md}` from this repo,
validates every manifest against the meta-schema, then atomically publishes:

  s3://agent-experiment-metadata-{env}/<id>/manifest.json
  s3://agent-experiment-metadata-{env}/<id>/instruction.md
  s3://agent-experiment-metadata-{env}/index.json   ← written LAST

`index.json` is the file every consumer (Lambda, broker, gp-api) reads first
to discover routing — uploading it last means readers never see a partial
publish where one experiment was updated and another wasn't.

`index.json` is GENERATED by this script and gitignored — never commit it.
The contract documented by the meta-schema + each `manifest.json` is the
source of truth; a hand-edited `experiments/index.json` would silently lose
any extra fields on the next publish (the script only emits a fixed set:
`{id, version, manifest_key, instruction_key, attachment_keys, hash}`).

Usage:
    AWS_PROFILE=work uv run python publish_experiments.py --env=dev

By default the publisher publishes the FULL set of experiments under
`experiments/<id>/`, regenerating `index.json` wholesale. The git branch is
the curation surface (develop → dev S3, qa → qa S3, master → prod S3).

Two dev-only affordances relax the wholesale model for pre-merge testing:

  --only <id>   Publish a single experiment to dev. Uploads just that
                experiment's files, then merges its entry into the LIVE
                index.json (insert if new, replace if existing), preserving
                every other live entry. Lets you iterate on one experiment,
                or stand up a brand-new one, without a full publish.

  sandbox       On a full dev publish, any LIVE index entry whose id contains
                "sandbox" is carried forward instead of dropped, so CI's
                develop publish does not clobber personal scratch experiments.

Both are gated to --env=dev. qa and prod always publish the full canonical
set with no preservation, so a partial/mixed state can never reach prod and
sandbox experiments can never leak past dev. Promote real experiments by
merging branches.

In CI: GH Actions assumes an AWS role via OIDC (no long-lived credentials) —
see `.github/workflows/publish-experiments.yml` for the role ARN. Note: a dev
publish now also needs `s3:GetObject` on the bucket's `index.json` (it reads
the live index to merge/preserve), not just `s3:PutObject`.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path

import boto3
from botocore.exceptions import ClientError
from jsonschema import Draft7Validator

REPO_ROOT = Path(__file__).resolve().parents[2]
EXPERIMENTS_DIR = REPO_ROOT / "experiments"
META_SCHEMA_PATH = EXPERIMENTS_DIR / "_schema" / "manifest.schema.json"

VALID_ENVS = {"dev", "qa", "prod"}

# Experiments whose id contains this marker are personal/scratch experiments.
# On a FULL dev publish they are preserved (carried forward from the live
# index) rather than dropped, so CI's develop publish can't clobber someone's
# in-progress sandbox. Dev-only: qa/prod never preserve, so a sandbox id can
# never leak past dev. Substring match (not a prefix) so `sandbox_oppo`,
# `feliks_sandbox`, etc. all qualify.
SANDBOX_MARKER = "sandbox"

# Experiment ids are constrained to this pattern by the meta-schema (and the
# dispatch lambda's loader). We re-check it here when (a) accepting a --only
# target and (b) carrying a live index entry forward, so a malformed id can't
# become an S3 key path and drift/corruption in the live index can't propagate
# into a freshly published index.
# Anchor with \Z, not $: in Python `$` also matches just before a trailing
# newline, so `^...$` would accept "sandbox_x\n" and let a newline leak into an
# S3 key / path. \Z anchors at the true end of string.
_EXPERIMENT_ID_RE = re.compile(r"^[a-z][a-z0-9_]{0,63}\Z")


def _is_sandbox(experiment_id: str) -> bool:
    return SANDBOX_MARKER in experiment_id


def _carryforward_problem(entry: object) -> str | None:
    """Return None if a live index entry is safe to carry forward, else a short
    reason string (surfaced in the operator-facing drop warning).

    Safe means: well-formed id and the canonical `<id>/manifest.json` /
    `<id>/instruction.md` keys this publisher emits. Anything else is
    drift/corruption and is dropped rather than re-published (a freshly built
    entry is always canonical, so this only ever filters entries we did not
    author this run).
    """
    if not isinstance(entry, dict):
        return "not a JSON object"
    eid = entry.get("id")
    if not isinstance(eid, str) or not _EXPERIMENT_ID_RE.match(eid):
        return "id does not match the experiment-id pattern"
    if entry.get("manifest_key") != f"{eid}/manifest.json":
        return "manifest_key is not canonical"
    if entry.get("instruction_key") != f"{eid}/instruction.md":
        return "instruction_key is not canonical"
    # attachment_keys must all be canonical `<id>/attachments/<basename>` so the
    # guarantee is self-contained rather than relying on the broker to re-check
    # prefixes at read time. A prefix check alone is not enough: the suffix must
    # be a single flat filename — no `/`, no `.`/`..`, no control chars — or a
    # drifted key like `<id>/attachments/../../x` would be re-published with the
    # publisher's blessing (mirrors `_validate_attachments` on the disk side).
    attachment_keys = entry.get("attachment_keys", [])
    if not isinstance(attachment_keys, list):
        return "attachment_keys is not a list"
    prefix = f"{eid}/attachments/"
    for ak in attachment_keys:
        if not isinstance(ak, str) or not ak.startswith(prefix):
            return "attachment key outside the canonical attachments prefix"
        basename = ak[len(prefix):]
        if (
            not basename
            or "/" in basename
            or basename in (".", "..")
            or any(ord(c) < 0x20 or ord(c) == 0x7F for c in basename)
        ):
            return "attachment key suffix is not a flat safe filename"
    return None


def _valid_carryforward(entry: object) -> bool:
    return _carryforward_problem(entry) is None

# Total bytes cap across all attachments for a single experiment. Bounds the
# broker manifest payload (it streams all attachments in one envelope) and the
# runner's pre-task workspace-write step. Pick conservatively — bumping later
# is a one-line change; loosening too early invites a 100 MB sidecar.
ATTACHMENTS_TOTAL_SIZE_LIMIT_BYTES = 5 * 1024 * 1024


class AttachmentValidationError(ValueError):
    """Raised when an attachment fails publisher-side validation.

    Distinct subclass so callers/tests can match the specific failure surface
    without catching unrelated ValueErrors from JSON parsing or jsonschema.
    """


def _load_meta_schema() -> dict:
    return json.loads(META_SCHEMA_PATH.read_text())


def _experiment_dirs() -> list[Path]:
    return sorted(
        p for p in EXPERIMENTS_DIR.iterdir()
        if p.is_dir() and p.name != "_schema" and not p.name.startswith(".")
    )


def _hash_pair(
    manifest_bytes: bytes,
    instruction_bytes: bytes,
    attachments: list[tuple[str, bytes]] | None = None,
) -> str:
    """Hash the published bytes for an experiment.

    Attachments must be passed in stable order (relpath-sorted) — the hash is
    used by consumers to detect a publish drift, so the same inputs must
    always produce the same digest.
    """
    h = hashlib.sha256()
    h.update(manifest_bytes)
    h.update(instruction_bytes)
    for relpath, body in (attachments or []):
        h.update(relpath.encode("utf-8"))
        h.update(b"\x00")
        h.update(body)
    return "sha256:" + h.hexdigest()


def _attachment_files(exp_dir: Path) -> list[Path]:
    att_dir = exp_dir / "attachments"
    if not att_dir.is_dir():
        return []
    return sorted(p for p in att_dir.rglob("*") if p.is_file())


# Attachments are guaranteed UTF-8 text by `_validate_attachments`, so a
# single static content type is correct for every upload. Extension-derived
# Content-Type is an attacker-controlled surface — if the bucket is ever
# fronted by CloudFront, an attachment whose basename ends in `.html` would
# be served as text/html. The validation contract makes that moot: refuse
# non-UTF-8 at publish, label everything text/plain at upload.
ATTACHMENT_CONTENT_TYPE = "text/plain; charset=utf-8"


def _validate_attachments(exp_dir: Path) -> list[tuple[str, bytes]]:
    """Walk experiments/<id>/attachments/, validate each entry, return
    (relpath, body) tuples sorted by relpath.

    Fails loudly on the first violation — partial publishes are never safe.
    """
    att_dir = exp_dir / "attachments"
    files = _attachment_files(exp_dir)
    out: list[tuple[str, bytes]] = []
    total_bytes = 0
    for f in files:
        relpath = f.relative_to(att_dir).as_posix()
        # Path safety: only basenames, no traversal, no absolute paths.
        if relpath.startswith("/"):
            raise AttachmentValidationError(
                f"{exp_dir.name}/attachments/{relpath}: absolute paths are not allowed"
            )
        segments = relpath.split("/")
        if any(seg == ".." for seg in segments):
            raise AttachmentValidationError(
                f"{exp_dir.name}/attachments/{relpath}: '..' path segments are not allowed"
            )
        # `output/` prefix is checked BEFORE the nested-dir rule so that if
        # nested dirs are ever allowed in the future, this rule still fires
        # — the runtime risk (clobbering an in-flight artifact under
        # /workspace/output/) is independent of layout policy.
        if relpath.startswith("output/"):
            raise AttachmentValidationError(
                f"{exp_dir.name}/attachments/{relpath}: 'output/' is reserved for "
                "runtime artifacts and must not appear in attachments"
            )
        if len(segments) > 1:
            # Nested dirs under attachments/ are deliberately deferred — the
            # runner writes attachments directly under /workspace/ as
            # basenames, so a nested source would have ambiguous target shape.
            raise AttachmentValidationError(
                f"{exp_dir.name}/attachments/{relpath}: nested subdirectories under "
                "attachments/ are not allowed (use a flat layout for now)"
            )
        # Reject symlinks: a symlink inside attachments/ is an arbitrary-file-
        # read vector — `read_bytes()` would happily slurp the link target.
        # Also resolve and re-check containment as belt-and-braces against any
        # future path-resolution quirk (a file whose parents contain a link,
        # bind mounts, etc.).
        if f.is_symlink():
            raise AttachmentValidationError(
                f"{exp_dir.name}/attachments/{relpath}: symlinks are not allowed "
                "(arbitrary-file-read risk)"
            )
        resolved = f.resolve()
        att_root = att_dir.resolve()
        try:
            resolved.relative_to(att_root)
        except ValueError as e:
            raise AttachmentValidationError(
                f"{exp_dir.name}/attachments/{relpath}: resolves outside attachments/ dir"
            ) from e
        # Size check BEFORE read: a stray multi-GB file would OOM us before
        # the cap-after-read could reject it. stat() is O(1).
        size = f.stat().st_size
        if total_bytes + size > ATTACHMENTS_TOTAL_SIZE_LIMIT_BYTES:
            raise AttachmentValidationError(
                f"{exp_dir.name}/attachments/: total size {total_bytes + size} bytes "
                f"exceeds cap {ATTACHMENTS_TOTAL_SIZE_LIMIT_BYTES} bytes (5 MB)"
            )
        body = f.read_bytes()
        # Broker streams attachments as text envelopes; binary 500s every
        # fetch. Refuse non-UTF-8 at publish so the failure is visible in CI.
        try:
            body.decode("utf-8")
        except UnicodeDecodeError as e:
            raise AttachmentValidationError(
                f"{exp_dir.name}/attachments/{relpath}: not valid UTF-8 "
                "(binary attachments not supported)"
            ) from e
        total_bytes += size
        out.append((relpath, body))
    out.sort(key=lambda item: item[0])
    return out


def _validate_all(meta_schema: dict, dirs: list[Path]) -> None:
    """Fail loudly on any meta-schema violation BEFORE any S3 write."""
    validator = Draft7Validator(meta_schema)
    failed_names: list[str] = []
    for d in dirs:
        manifest_path = d / "manifest.json"
        instruction_path = d / "instruction.md"
        if not manifest_path.exists():
            print(f"  ✗ {d.name}: missing manifest.json", file=sys.stderr)
            failed_names.append(d.name)
            continue
        if not instruction_path.exists():
            print(f"  ✗ {d.name}: missing instruction.md", file=sys.stderr)
            failed_names.append(d.name)
            continue
        try:
            manifest = json.loads(manifest_path.read_text())
        except json.JSONDecodeError as e:
            print(f"  ✗ {d.name}: manifest.json invalid JSON: {e}", file=sys.stderr)
            failed_names.append(d.name)
            continue
        # absolute_path mixes strings (object keys) and ints (array indices);
        # coerce to str so Python 3 doesn't raise TypeError on mixed-type
        # comparison mid-sort and crash CI on a malformed manifest.
        errors = sorted(validator.iter_errors(manifest), key=lambda e: [str(p) for p in e.absolute_path])
        if errors:
            print(f"  ✗ {d.name}: {len(errors)} schema violation(s):", file=sys.stderr)
            for err in errors:
                path = ".".join(str(p) for p in err.absolute_path) or "<root>"
                print(f"      {path}: {err.message}", file=sys.stderr)
            failed_names.append(d.name)
            continue
        if manifest.get("id") != d.name:
            print(
                f"  ✗ {d.name}: manifest id '{manifest.get('id')}' does not match dir name",
                file=sys.stderr,
            )
            failed_names.append(d.name)
            continue
        # Attachment validation runs alongside meta-schema validation so a
        # bad sidecar surfaces in the same pre-flight wave as a bad manifest
        # — no half-validated state where the manifest is OK but an
        # attachment kills the publish mid-upload.
        try:
            attachments = _validate_attachments(d)
        except AttachmentValidationError as e:
            print(f"  ✗ {d.name}: attachment validation failed: {e}", file=sys.stderr)
            failed_names.append(d.name)
            continue
        att_summary = f", {len(attachments)} attachment(s)" if attachments else ""
        print(f"  ✓ {d.name} v{manifest['version']}{att_summary}")
    if failed_names:
        # A bare `sys.exit(1)` left operators scrolling back through the
        # ✗ lines counting failures by hand. Surface the count + names so
        # the failure summary is actionable on its own line.
        print(
            f"\n  FAILED: {len(failed_names)} of {len(dirs)} experiments rejected — "
            f"see ✗ lines above ({', '.join(failed_names)})",
            file=sys.stderr,
        )
        sys.exit(1)


def _resolve_json_pointer(root: dict, pointer: str):
    """Walk a JSON Pointer path like `districtInputs/properties/state` against
    the meta-schema's $defs root. Returns the targeted node or raises ValueError."""
    node = root
    for segment in pointer.split("/"):
        if not segment:
            continue
        if not isinstance(node, dict) or segment not in node:
            raise ValueError(f"$ref segment {segment!r} not found in path {pointer!r}")
        node = node[segment]
    return node


def _inline_refs(node, defs: dict):
    """Recursively inline `{"$ref": "../_schema/manifest.schema.json#/$defs/X"}`
    (and nested forms like `#/$defs/X/properties/Y`) into the actual referenced
    object. Source manifests stay DRY; published manifests are self-contained so
    consumers don't need a $ref resolver.

    Only handles `$ref` pointing at the meta-schema's `$defs` namespace. Other
    refs pass through unchanged so a future absolute-URI ref doesn't get
    silently broken.
    """
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and "#/$defs/" in ref:
            pointer = ref.split("#/$defs/", 1)[1]
            try:
                target = _resolve_json_pointer(defs, pointer)
            except ValueError as e:
                raise ValueError(f"$ref points at unknown $defs entry: {ref} ({e})") from e
            # Recurse — the target might itself contain $refs
            return _inline_refs(target, defs)
        return {k: _inline_refs(v, defs) for k, v in node.items()}
    if isinstance(node, list):
        return [_inline_refs(item, defs) for item in node]
    return node


def _publishable_manifest_bytes(manifest_path: Path, defs: dict) -> bytes:
    """Read a manifest from disk and emit the bytes to publish — with all
    `$ref`s into the meta-schema's `$defs` inlined so the published artifact
    is self-contained at runtime."""
    raw = json.loads(manifest_path.read_text())
    inlined = _inline_refs(raw, defs)
    # Strip the $schema editor pointer — it references a relative path that
    # doesn't exist in S3, and runtime consumers ignore it anyway.
    inlined.pop("$schema", None)
    return json.dumps(inlined, indent=2, sort_keys=True).encode() + b"\n"


def _build_entries(
    dirs: list[Path], meta: dict
) -> tuple[list[dict], dict[str, list[tuple[str, bytes]]]]:
    """Build the index.json entries for every experiment in `dirs`.

    Returns the entries list AND a per-experiment attachments map. The map lets
    `publish()` upload the EXACT bytes that fed the hash digest; re-reading from
    disk at upload time created a TOCTOU window where a concurrent edit could
    ship bytes that don't match the published digest.

    `publish()` wraps these entries in the index envelope (published_at /
    git_sha) so that envelope is constructed in exactly one place.

    The hash field covers the *published* manifest bytes (post-$ref-inlining)
    + instruction + every attachment body. Attachments contribute to the hash
    in relpath-sorted order so the digest is stable across machines.
    """
    defs = meta.get("$defs", {})
    entries = []
    attachments_by_id: dict[str, list[tuple[str, bytes]]] = {}
    for d in dirs:
        manifest_path = d / "manifest.json"
        instruction_path = d / "instruction.md"
        manifest_bytes = _publishable_manifest_bytes(manifest_path, defs)
        instruction_bytes = instruction_path.read_bytes()
        attachments = _validate_attachments(d)
        manifest = json.loads(manifest_bytes)
        attachment_keys = sorted(
            f"{manifest['id']}/attachments/{relpath}" for relpath, _ in attachments
        )
        attachments_by_id[manifest["id"]] = attachments
        entries.append({
            "id": manifest["id"],
            "version": manifest["version"],
            "manifest_key": f"{manifest['id']}/manifest.json",
            "instruction_key": f"{manifest['id']}/instruction.md",
            "attachment_keys": attachment_keys,
            "hash": _hash_pair(manifest_bytes, instruction_bytes, attachments),
        })
    return entries, attachments_by_id


def _fetch_live_index(s3, bucket: str) -> dict | None:
    """GET the live index.json. Returns the parsed dict, or None when the
    index does not exist yet (fresh bucket).

    Raises on a corrupt/malformed live index rather than returning None:
    silently proceeding would let a --only or dev publish clobber every other
    entry it was supposed to preserve.
    """
    try:
        resp = s3.get_object(Bucket=bucket, Key="index.json")
    except ClientError as e:
        code = e.response.get("Error", {}).get("Code", "")
        if code in ("NoSuchKey", "404"):
            return None
        print(
            f"  ✗ S3 GetObject failed for s3://{bucket}/index.json: {e}",
            file=sys.stderr,
        )
        raise
    body = resp["Body"].read()
    try:
        payload = json.loads(body)
    except (json.JSONDecodeError, ValueError) as e:
        raise RuntimeError(
            f"live index s3://{bucket}/index.json is not valid JSON; refusing "
            f"to publish (a merge would clobber other entries): {e}"
        ) from e
    if not isinstance(payload, dict) or not isinstance(payload.get("experiments"), list):
        raise RuntimeError(
            f"live index s3://{bucket}/index.json is missing an 'experiments' "
            "array; refusing to publish (would clobber other entries)"
        )
    return payload


def _compose_index_entries(
    new_entries: list[dict],
    live_entries: list[object],
    *,
    only_id: str | None,
    env: str,
    on_drop: Callable[[object, str], None] | None = None,
) -> list[dict]:
    """Decide the final `experiments` list to write to index.json.

    - `--only <id>` (dev): keep every live entry except <id>, then add the
      freshly built entry for <id> (insert or replace). Preserves all others.
    - full publish, dev: canonical entries, plus any live entry whose id is a
      sandbox (`_is_sandbox`) and is not already canonical. Canonical wins on
      an id collision.
    - full publish, qa/prod: canonical entries only (no preservation).

    Carried-forward live entries are filtered through `_carryforward_problem`,
    so a drifted/corrupt live entry (including a non-dict array element or a
    duplicate id) is dropped rather than re-published. Freshly built entries
    are always canonical and are never filtered. `on_drop`, if given, is called
    with each dropped candidate and the reason, so the caller can surface the
    drift instead of losing it silently.

    No I/O of its own (the only side effect is the `on_drop` callback), so the
    policy is unit-testable without S3.
    """
    # publish() already rejects --only for qa/prod at the CLI boundary; enforce
    # the same invariant here so no future caller can merge a partial publish
    # into a qa/prod index by skipping that guard.
    if only_id is not None and env != "dev":
        raise ValueError(f"--only merge is dev-only; got env={env!r}")

    def _drop(entry: object, why: str) -> None:
        if on_drop is not None:
            on_drop(entry, why)

    def _carry(candidates: list[dict]) -> list[dict]:
        kept: list[dict] = []
        seen_ids: set[str] = set()
        for e in candidates:
            problem = _carryforward_problem(e)
            if problem is None and e["id"] in seen_ids:
                # The live index should be unique by id; if drift produced
                # duplicates, keep the first and drop the rest rather than
                # amplifying the corruption into the fresh index.
                problem = "duplicate id in live index"
            if problem is not None:
                _drop(e, problem)
                continue
            seen_ids.add(e["id"])
            kept.append(e)
        return kept

    # A live `experiments` element that isn't even an object is drift; drop it
    # (surfaced via on_drop) before any per-path `.get()` access can crash.
    live_dicts: list[dict] = []
    for e in live_entries:
        if isinstance(e, dict):
            live_dicts.append(e)
        else:
            _drop(e, "not a JSON object")

    if only_id is not None:
        kept = _carry([e for e in live_dicts if e.get("id") != only_id])
        merged = kept + new_entries
    elif env == "dev":
        canonical_ids = {e.get("id") for e in new_entries}
        candidates = [
            e
            for e in live_dicts
            if _is_sandbox(str(e.get("id", ""))) and e.get("id") not in canonical_ids
        ]
        merged = new_entries + _carry(candidates)
    else:
        merged = new_entries
    return sorted(merged, key=lambda e: str(e.get("id", "")))


def _git_sha() -> str:
    import subprocess
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO_ROOT, capture_output=True, text=True, check=True,
        )
        return out.stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        # Surface the fallback so an operator can spot a misconfigured CI
        # runner. Silent "unknown" git_sha in index.json hides provenance
        # gaps for weeks otherwise.
        print(
            f"warning: git rev-parse failed ({type(e).__name__}); "
            "index.json will record git_sha='unknown'",
            file=sys.stderr,
        )
        return "unknown"


def _upload(s3, bucket: str, key: str, body: bytes, content_type: str) -> None:
    try:
        s3.put_object(Bucket=bucket, Key=key, Body=body, ContentType=content_type)
    except ClientError as e:
        print(f"  ✗ S3 PutObject failed for s3://{bucket}/{key}: {e}", file=sys.stderr)
        raise


def publish(env: str, dry_run: bool = False, only: str | None = None) -> int:
    if env not in VALID_ENVS:
        print(f"error: --env must be one of {sorted(VALID_ENVS)}", file=sys.stderr)
        return 1
    # --only is a dev-only affordance. qa/prod must publish the full canonical
    # set via branch promotion so a partial/mixed state can never reach prod.
    if only is not None and env != "dev":
        print(
            "error: --only is dev-only. qa/prod publish the full canonical set "
            "via branch promotion (no partial/mixed prod state).",
            file=sys.stderr,
        )
        return 1

    bucket = f"agent-experiment-metadata-{env}"

    if only is not None:
        # Validate before any filesystem touch: the id pattern (same as the
        # meta-schema / lambda) rejects path separators, dotfiles, and _schema,
        # so `--only` can never resolve outside experiments/ or become a bad key.
        if not _EXPERIMENT_ID_RE.match(only):
            print(
                f"error: --only '{only}' is not a valid experiment id "
                f"(must match {_EXPERIMENT_ID_RE.pattern})",
                file=sys.stderr,
            )
            return 1
        target = EXPERIMENTS_DIR / only
        if not target.is_dir():
            available = ", ".join(d.name for d in _experiment_dirs())
            print(
                f"error: no experiment dir 'experiments/{only}/'. "
                f"Available: {available}",
                file=sys.stderr,
            )
            return 1
        dirs = [target]
    else:
        dirs = _experiment_dirs()
        if not dirs:
            print(
                f"error: no experiment dirs found under {EXPERIMENTS_DIR}",
                file=sys.stderr,
            )
            return 1

    scope_label = f"experiment '{only}'" if only else f"{len(dirs)} experiment(s)"
    print(f"== validating {scope_label} against meta-schema ==")
    meta = _load_meta_schema()
    _validate_all(meta, dirs)

    new_entries, attachments_by_id = _build_entries(dirs, meta)
    defs = meta.get("$defs", {})
    git_sha = _git_sha()

    mode = f"--only {only}" if only else "full set"
    print(f"\n== publish target: s3://{bucket}/  (env={env}, mode={mode}, git={git_sha}) ==")
    print(f"   {len(new_entries)} experiment(s) to upload")

    if dry_run:
        print("\n[DRY RUN] would upload (manifest.json + instruction.md + attachments per experiment):")
        for entry in new_entries:
            # `entry['hash']` is "sha256:<64 hex chars>"; an unconditional
            # [:23] slice cut the prefix mid-word ("sha256:xxxxxxxxxxxxxxxx").
            # Strip prefix, slice the hex, then re-tag explicitly.
            short_hex = entry["hash"].removeprefix("sha256:")[:12]
            print(f"   {entry['id']} v{entry['version']} (sha256:{short_hex}...)")
            print(f"     - {entry['manifest_key']}")
            print(f"     - {entry['instruction_key']}")
            atts = attachments_by_id.get(entry["id"], [])
            att_total = 0
            # Bodies are already in the cached map — print byte counts so
            # the operator can see cap-proximity at-a-glance, and surface
            # the per-experiment subtotal against the 5 MB cap.
            for ak, (_relpath, body) in zip(entry["attachment_keys"], atts, strict=True):
                size = len(body)
                att_total += size
                print(f"     - {ak} ({size:,} bytes)")
            if atts:
                print(
                    f"     (attachments subtotal: {att_total:,} bytes of "
                    f"{ATTACHMENTS_TOTAL_SIZE_LIMIT_BYTES:,} cap)"
                )
        if only is not None:
            print(
                f"\n[DRY RUN] index.json: would MERGE entry '{only}' into the live "
                "index, preserving all other live entries."
            )
        elif env == "dev":
            print(
                "\n[DRY RUN] index.json: would write the full canonical set, "
                "PRESERVING any live 'sandbox' entries."
            )
        else:
            print("\n[DRY RUN] index.json: would write the full canonical set (wholesale).")
        return 0

    s3 = boto3.client("s3")

    # Compose the final index. For --only (dev) and full dev publishes we merge
    # against the LIVE index so we don't clobber other experiments / sandbox
    # scratch. qa/prod take the canonical set verbatim (wholesale).
    #
    # This GET-merge-PUT is not atomic: a concurrent publish between the read
    # and the index write can lose this merge. Accepted for dev (re-run if a
    # develop CI publish races you); qa/prod don't merge, so no race there.
    live_entries: list[dict] = []
    if only is not None or env == "dev":
        live_index = _fetch_live_index(s3, bucket)
        if live_index is not None:
            live_entries = live_index.get("experiments", [])
    dropped: list[str] = []

    def _record_drop(entry: object, why: str) -> None:
        eid = entry.get("id", "<no-id>") if isinstance(entry, dict) else "<not-an-object>"
        dropped.append(f"{eid} ({why})")

    final_entries = _compose_index_entries(
        new_entries, live_entries, only_id=only, env=env, on_drop=_record_drop,
    )
    if dropped:
        # Drift in the live index: an entry we would have carried forward had
        # non-canonical keys. We drop it (don't re-publish corruption) but say so.
        print(
            f"   ⚠ dropped {len(dropped)} malformed live index entr(ies), "
            f"not carry-forward safe: {', '.join(dropped)}",
            file=sys.stderr,
        )

    # Upload per-experiment files (only the ones we built) in parallel, then
    # index.json LAST so readers never see a partial publish. The executor join
    # (`as_completed` loop) surfaces any per-file failures BEFORE the switch.
    with ThreadPoolExecutor(max_workers=10) as ex:
        futures = []
        for entry in new_entries:
            exp_dir = EXPERIMENTS_DIR / entry["id"]
            # Inline $refs so the published manifest is self-contained — the
            # Lambda's Draft7Validator has no resolver for the meta-schema.
            manifest_bytes = _publishable_manifest_bytes(exp_dir / "manifest.json", defs)
            instruction_bytes = (exp_dir / "instruction.md").read_bytes()
            futures.append(ex.submit(
                _upload, s3, bucket, entry["manifest_key"],
                manifest_bytes, "application/json",
            ))
            futures.append(ex.submit(
                _upload, s3, bucket, entry["instruction_key"],
                instruction_bytes, "text/markdown",
            ))
            # Use the bytes captured during validation — the same bytes that
            # fed the hash digest. Re-reading from disk would open a TOCTOU
            # window where a concurrent edit could ship bytes that don't
            # match the published digest.
            atts = attachments_by_id.get(entry["id"], [])
            for ak, (_relpath, body) in zip(entry["attachment_keys"], atts, strict=True):
                futures.append(ex.submit(
                    _upload, s3, bucket, ak,
                    body, ATTACHMENT_CONTENT_TYPE,
                ))
        for f in as_completed(futures):
            f.result()  # surface failures before writing index.json

    for entry in new_entries:
        att_count = len(entry["attachment_keys"])
        att_summary = f" + {att_count} attachment(s)" if att_count else ""
        print(f"   ✓ {entry['id']} v{entry['version']}{att_summary}")

    preserved_count = len(final_entries) - len(new_entries)
    if preserved_count > 0:
        print(f"   ↳ preserved {preserved_count} existing index entr(ies)")

    index_out = {
        "published_at": datetime.now(timezone.utc).isoformat(),
        "git_sha": git_sha,
        "experiments": final_entries,
    }
    print("\n== writing index.json (atomic switch) ==")
    _upload(s3, bucket, "index.json",
            (json.dumps(index_out, indent=2) + "\n").encode(),
            "application/json")
    print(f"   ✓ s3://{bucket}/index.json ({len(final_entries)} experiments live)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--env", required=True, help="Target env: dev | qa | prod")
    parser.add_argument("--dry-run", action="store_true",
                        help="Validate + show what would publish, do not touch S3")
    parser.add_argument(
        "--only", metavar="EXPERIMENT_ID", default=None,
        help="Publish just this one experiment (dev only). Uploads its files "
             "and merges its entry into the live index.json, preserving every "
             "other entry. Inserts if new, replaces if existing.",
    )
    args = parser.parse_args()
    return publish(env=args.env, dry_run=args.dry_run, only=args.only)


if __name__ == "__main__":
    raise SystemExit(main())
